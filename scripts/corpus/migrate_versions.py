"""Collapse command_docs version blocks into one body (corpus spec, section A).

One body per command; facts that bind to a subset of versions carry them:

- File availability: ``availability: {"versions": [...]}``, omitted when the
  doc covers every version of its home tree (engine directory or `_common`).
- A field whose value genuinely differs between versions becomes a version
  map: ``"syntax": {"7.0": "...", "9.0": "..."}`` — any field, resolved by
  the loader at request time; a version absent from the map omits the field.
- keywords/examples merge entry-by-entry (keyed by name/command plus ordinal
  for duplicates); an entry carries ``availability.versions`` when it is not
  in every version, and per-field version maps where its text changed.
- The removed-command apparatus folds away: ``reason``/``source_urls``/
  ``target_version`` become one note per removed version;
  ``legacy_documentation`` provenance becomes ``verification`` entries;
  block-level ``source`` merges into the top-level ``source``.
- ``figure_reference`` flags are derived data: dropped here and regenerated by
  ``flag_figure_defined.py`` on the merged shape.
- A file whose every version block is ``available: false`` keeps top-level
  ``available: false`` (negative knowledge, e.g. 3DEC ``fblock delete``).

Usage:
    uv run python scripts/corpus/migrate_versions.py [--write]
"""

from __future__ import annotations

import json
import sys
from collections import Counter
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

RESOURCES = Path(__file__).resolve().parents[2] / "src" / "itasca_mcp" / "knowledge" / "resources"

VERSION_ORDER = ("6.0", "7.0", "9.0")


@dataclass
class Stats:
    files: int = 0
    version_maps: int = 0
    entry_availability: int = 0
    tomb_notes: list[str] = field(default_factory=list)
    oddities: list[str] = field(default_factory=list)


def vsorted(versions: Any) -> list[str]:
    materialised = set(versions)
    return [v for v in VERSION_ORDER if v in materialised]


def equalish(values: list[Any]) -> bool:
    first = json.dumps(values[0], sort_keys=True)
    return all(json.dumps(v, sort_keys=True) == first for v in values[1:])


def strip_figures(node: Any) -> None:
    if isinstance(node, dict):
        node.pop("figure_reference", None)
        for v in node.values():
            strip_figures(v)
    elif isinstance(node, list):
        for v in node:
            strip_figures(v)


def merge_field(values: dict[str, Any], available: list[str], stats: Stats) -> Any:
    """Scalar if identical and total, else a version map."""
    if len(values) == len(available) and equalish(list(values.values())):
        return next(iter(values.values()))
    stats.version_maps += 1
    return {v: values[v] for v in vsorted(values)}


def merge_entries(
    per_version: dict[str, list[Any]], available: list[str], rel: str, kind: str, stats: Stats
) -> list[Any]:
    ident_key = "name" if kind == "keywords" else "command"
    keyed: dict[tuple[str, int], dict[str, dict[str, Any]]] = {}
    orders: dict[str, list[tuple[str, int]]] = {}
    for version, entries in per_version.items():
        counts: Counter[str] = Counter()
        order = []
        for entry in entries:
            if not isinstance(entry, dict):
                stats.oddities.append(f"{rel}: non-dict {kind} entry {entry!r}")
                return [e for e in per_version[available[-1]]]
            ident = str(entry.get(ident_key, json.dumps(entry, sort_keys=True)))
            key = (ident, counts[ident])
            counts[ident] += 1
            keyed.setdefault(key, {})[version] = entry
            order.append(key)
        orders[version] = order

    union: list[tuple[str, int]] = []
    for version in vsorted(per_version):
        prev = -1
        for key in orders[version]:
            if key in union:
                prev = union.index(key)
            else:
                prev += 1
                union.insert(prev, key)

    def build(variants: dict[str, dict[str, Any]], availability_base: dict[str, Any]) -> dict[str, Any]:
        entry_versions = vsorted(variants)
        field_order: list[str] = []
        for version in entry_versions:
            for name in variants[version]:
                if name not in field_order:
                    field_order.append(name)
        out: dict[str, Any] = {}
        extra_availability = dict(availability_base)
        for name in field_order:
            if name == "availability":
                continue
            values = {v: variants[v][name] for v in entry_versions if name in variants[v]}
            out[name] = merge_field(values, entry_versions, stats)
        if entry_versions != available:
            extra_availability["versions"] = entry_versions
            stats.entry_availability += 1
        if extra_availability:
            out["availability"] = extra_availability
        return out

    merged = []
    for key in union:
        variants = keyed[key]
        entry_versions = vsorted(variants)
        availabilities = {v: variants[v].get("availability") for v in entry_versions}
        distinct = {json.dumps(a, sort_keys=True) for a in availabilities.values()}
        if len(distinct) == 1:
            merged.append(build(variants, dict(availabilities[entry_versions[0]] or {})))
            continue
        # An untagged 6.0 block is pfc-only by construction: a 7.0/9.0 engines
        # tag that includes pfc states the same fact for every requestable pair.
        tagged = {json.dumps(a, sort_keys=True) for v, a in availabilities.items() if v != "6.0"}
        base = availabilities[[v for v in entry_versions if v != "6.0"][0]] if len(tagged) == 1 else None
        if (
            len(tagged) == 1
            and availabilities.get("6.0") is None
            and isinstance(base, dict)
            and "pfc" in base.get("engines", [])
        ):
            merged.append(build(variants, dict(base)))
            continue
        # Genuinely version-dependent engine scoping: one entry per tag value.
        groups: dict[str, list[str]] = {}
        for version in entry_versions:
            groups.setdefault(json.dumps(availabilities[version], sort_keys=True), []).append(version)
        for tag_json, group_versions in groups.items():
            tag = json.loads(tag_json) or {}
            merged.append(build({v: variants[v] for v in group_versions}, dict(tag)))
    return merged


def tombstone_notes(version: str, block: dict[str, Any], rel: str, stats: Stats) -> tuple[list[str], list[str]]:
    """Notes + verification derived from an available-false block."""
    notes: list[str] = []
    verification: list[str] = []
    reason = block.get("reason")
    urls = block.get("source_urls", [])
    if reason:
        text = f"Not available in {version}: {reason}"
        if urls:
            text += f" ({', '.join(urls)})"
        notes.append(text)
    for note in block.get("notes", []):
        notes.append(note if version in note else f"{version}: {note}")
    unknown = set(block) - {"available", "reason", "source_urls", "target_version", "command", "notes"}
    if unknown:
        stats.oddities.append(f"{rel}: tombstone block keys {sorted(unknown)}")
    stats.tomb_notes.extend(f"{rel} [{version}] {n}" for n in notes)
    return notes, verification


def legacy_verification(version: str, legacy: dict[str, Any], rel: str, stats: Stats) -> str:
    source = legacy.get("source", "the official command index")
    urls = ", ".join(legacy.get("source_urls", []))
    text = f"{version}: availability verified against {source}"
    if urls:
        text += f" ({urls})"
    basis = legacy.get("syntax_basis")
    if basis:
        text += f"; syntax from {basis}"
    unknown = set(legacy) - {"availability_verified", "source", "source_urls", "syntax_basis", "target_version"}
    if unknown:
        stats.oddities.append(f"{rel}: legacy_documentation keys {sorted(unknown)}")
    return text + "."


def migrate_file(doc: dict[str, Any], rel: str, stats: Stats) -> dict[str, Any] | None:
    versions = doc.get("versions")
    if not isinstance(versions, dict):
        stats.oddities.append(f"{rel}: no versions dict")
        return None
    strip_figures(doc)

    blocks = {v: dict(b) for v, b in versions.items()}
    available = vsorted(v for v, b in blocks.items() if b.get("available") is not False)
    tombs = {v: b for v, b in blocks.items() if b.get("available") is False}

    extra_notes: list[str] = []
    extra_verification: list[str] = []
    for version in vsorted(tombs):
        notes, verification = tombstone_notes(version, tombs[version], rel, stats)
        extra_notes.extend(notes)
        extra_verification.extend(verification)

    sources: list[str] = []
    for version in available:
        block = blocks[version]
        if "legacy_documentation" in block:
            extra_verification.append(legacy_verification(version, block.pop("legacy_documentation"), rel, stats))
        if "source" in block:
            value = block.pop("source")
            for url in [value] if isinstance(value, str) else value:
                if url not in sources:
                    sources.append(url)
        if "version_notes" in block:  # one flac file; the texts name their versions
            extra_notes.extend(block.pop("version_notes"))
        unknown = set(block) - {"command", "syntax", "description", "keywords", "examples", "notes"}
        if unknown:
            stats.oddities.append(f"{rel}: block [{version}] keys {sorted(unknown)}")

    out: dict[str, Any] = {}
    top = {k: v for k, v in doc.items() if k != "versions"}

    if not available:  # full tombstone: negative knowledge, no body
        out.update(top)
        out["available"] = False
        if extra_notes:
            out.setdefault("notes", [])
            out["notes"] = list(out["notes"]) + extra_notes
        return out

    block_fields: list[str] = []
    for version in available:
        for name in blocks[version]:
            if name not in block_fields:
                block_fields.append(name)

    def merged_value(name: str) -> Any:
        values = {
            v: (blocks[v][name] if name in blocks[v] else top[name])
            for v in available
            if name in blocks[v] or name in top
        }
        if name in ("keywords", "examples") and all(isinstance(x, list) for x in values.values()):
            if len(values) == len(available):
                return merge_entries(values, available, rel, name, stats)
            # present only in some versions: keep fidelity with a version map
            return merge_field(values, available, stats)
        return merge_field(values, available, stats)

    done = set()
    for name, value in top.items():
        if name in ("keywords", "examples") or name in block_fields:
            out[name] = merged_value(name)
        else:
            out[name] = value
        done.add(name)
    # Always explicit: the advertised list replaces it in place when serving.
    out["availability"] = {"versions": available}
    for name in block_fields:
        if name not in done:
            out[name] = merged_value(name)

    if sources:
        existing = out.get("source")
        merged_sources = ([existing] if isinstance(existing, str) else list(existing or [])) + [
            s for s in sources if s not in (existing if isinstance(existing, list) else [existing])
        ]
        out["source"] = merged_sources[0] if len(merged_sources) == 1 else merged_sources
    if extra_notes:
        notes_value = out.get("notes")
        if isinstance(notes_value, dict):  # version map: append to every branch
            for branch in notes_value.values():
                branch.extend(extra_notes)
        else:
            out["notes"] = list(notes_value or []) + extra_notes
    if extra_verification:
        out["verification"] = list(out.get("verification", [])) + extra_verification
    return out


def main() -> int:
    write = "--write" in sys.argv
    stats = Stats()
    for path in sorted(RESOURCES.glob("*/command_docs/commands/**/*.json")):
        rel = path.relative_to(RESOURCES).as_posix()
        doc = json.loads(path.read_text(encoding="utf-8"))
        merged = migrate_file(doc, rel, stats)
        if merged is None:
            continue
        stats.files += 1
        if write:
            path.write_text(json.dumps(merged, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")

    print("TOMBSTONE NOTES:")
    print("\n".join(stats.tomb_notes))
    print(
        f"\nfiles: {stats.files}; version maps: {stats.version_maps}; "
        f"entries with availability: {stats.entry_availability}" + ("" if write else " (dry run)")
    )
    if stats.oddities:
        print("\nODDITIES:")
        print("\n".join(sorted(set(stats.oddities))[:60]))
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
